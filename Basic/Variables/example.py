#Exemmplo 1:

# string (str) → texto
nome = "João"
print("Nome:", nome)

# integer (int) → número inteiro
idade = 19
print("Idade:", idade)

# float → número decimal
altura = 1.75
print("Altura:", altura)

# boolean (bool) → verdadeiro ou falso
maior_de_idade = True
print("Maior de idade?", maior_de_idade)

#Exemplo 2:
nome = input("Digite seu nome: ")
idade = int(input("Digite sua idade: "))
altura = float(input("Digite sua altura: "))

print(f"Olá {nome}")
print(f"Você tem {idade} anos")
print(f"Sua altura é {altura}")